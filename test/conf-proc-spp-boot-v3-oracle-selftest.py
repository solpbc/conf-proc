def _frame(value: bytes) -> bytes:
    return len(value).to_bytes(8, "big") + value


def _measurement(*values: bytes) -> bytes:
    if len(values) != 13 or any(type(value) is not bytes for value in values):
        raise ValueError(CP_BOOT_V3_PCR)
    return hashlib.sha256(DOMAIN_V3 + b"".join(_frame(value) for value in values)).digest()


def _predicted_pcr(measurement: bytes) -> bytes:
    if type(measurement) is not bytes or len(measurement) != 32:
        raise ValueError(CP_BOOT_V3_PCR)
    return hashlib.sha256(b"\0" * 32 + measurement).digest()


