def _accept_controls(controls: object) -> None:
    if type(controls) is not dict or tuple(controls) != CONTROL_NAMES_V3:
        raise ValueError(CP_BOOT_V3_CONTROL)
    modules = controls["modules"]
    if modules != (0, 1, KERNEL_READBACK_IDENTITY_V3, True):
        raise ValueError(CP_BOOT_V3_CONTROL)
    kexec = controls["kexec"]
    if type(kexec) is not tuple or len(kexec) != 5 or kexec[0] not in (0, 1) or kexec[1] != 1 or kexec[2] not in ("integrity", "confidentiality") or kexec[3] is not True or kexec[4] != KERNEL_READBACK_IDENTITY_V3:
        raise ValueError(CP_BOOT_V3_CONTROL)
    sysrq = controls["sysrq"]
    if type(sysrq) is not tuple or len(sysrq) != 3 or not _is_exact_int(sysrq[0]) or not 0 <= sysrq[0] <= 511 or sysrq[1:] != (0, KERNEL_READBACK_IDENTITY_V3):
        raise ValueError(CP_BOOT_V3_CONTROL)
    unprivileged_bpf = controls["unprivileged_bpf"]
    if type(unprivileged_bpf) is not tuple or len(unprivileged_bpf) != 3 or unprivileged_bpf[0] not in (0, 1, 2) or unprivileged_bpf[1:] != (1, KERNEL_READBACK_IDENTITY_V3):
        raise ValueError(CP_BOOT_V3_CONTROL)
    userfaultfd = controls["userfaultfd"]
    if type(userfaultfd) is not tuple or len(userfaultfd) != 3 or userfaultfd[0] not in (0, 1) or userfaultfd[1:] != (0, KERNEL_READBACK_IDENTITY_V3):
        raise ValueError(CP_BOOT_V3_CONTROL)
    kernel_debug = controls["kernel_debug"]
    if type(kernel_debug) is not tuple or len(kernel_debug) != 7:
        raise ValueError(CP_BOOT_V3_CONTROL)
    kptr, dmesg, perf, ptrace, debugfs_present, kcore_accessible, debug_identity = kernel_debug
    if (
        type(kptr) is not tuple or kptr[0] not in (0, 1, 2) or kptr[1] != 2
        or type(dmesg) is not tuple or dmesg[0] not in (0, 1) or dmesg[1] != 1
        or type(perf) is not tuple or perf[0] not in (-1, 0, 1, 2, 3, 4) or perf[1] != max(perf[0], 3) or perf[1] not in (3, 4)
        or type(ptrace) is not tuple or ptrace[0] not in (0, 1, 2, 3) or ptrace[1] != 3
        or debugfs_present is not False or kcore_accessible is not False or debug_identity != KERNEL_READBACK_IDENTITY_V3
    ):
        raise ValueError(CP_BOOT_V3_CONTROL)
    if controls["recovery_operator_ingress"] != RECOVERY_ABSENT_V3:
        raise ValueError(CP_BOOT_V3_CONTROL)
    writable_roots = controls["writable_roots"]
    if writable_roots != (WRITABLE_ROOT_REQUIREMENTS_V3, MOUNT_READBACK_IDENTITY_V3):
        raise ValueError(CP_BOOT_V3_CONTROL)
    tpm_closure = controls["tpm_closure"]
    if tpm_closure != (TPM_CLOSURE_REQUIREMENTS_V3, TPM_READBACK_IDENTITY_V3):
        raise ValueError(CP_BOOT_V3_CONTROL)
    persistence = controls["persistence"]
    if persistence != (PERSISTENCE_REQUIREMENTS_V3, MOUNT_READBACK_IDENTITY_V3):
        raise ValueError(CP_BOOT_V3_CONTROL)


def _resolved_dev_rows(registrations: dict[str, int]) -> tuple[tuple[object, ...], ...]:
    rows = []
    for path, kind, major_kind, major_or_key, minor, mode, uid, gid in DEV_ROWS_V3:
        major = major_or_key if major_kind == "literal" else registrations[major_or_key]
        rows.append((path, kind, major, minor, mode, uid, gid))
    return tuple(rows)


def _forbidden_dev_path(path: str) -> bool:
    allowed = {row[0] for row in DEV_ROWS_V3} | {row[0] for row in DEV_DIRECTORIES_V3}
    return (
        path in {"/dev/tpm0", "/dev/mapper/control", "/dev/kmsg", "/dev/mem", "/dev/kmem", "/dev/port"}
        or path.startswith("/dev/dm-")
        or path.startswith("/dev/tty")
        or path == "/dev/ptmx"
        or path.startswith("/dev/pts/")
        or path.startswith("/dev/dri/")
        or (path.startswith("/dev/nvidia") and path not in allowed)
        or path.startswith("/dev/block/")
    )


def _accept_dev_tree(
    directories: object,
    nodes: object,
    registrations: object,
    other_nodes: object,
) -> None:
    if directories != DEV_DIRECTORIES_V3 or type(registrations) is not dict or set(registrations) != {"tpm_rm", "nvidia_gpu", "nvidia_uvm", "nvidia_caps"}:
        raise ValueError(CP_BOOT_V3_DEV_TREE)
    if any(type(value) is not int for value in registrations.values()):
        raise ValueError(CP_BOOT_V3_DEV_TREE)
    if len(set(registrations.values())) != 4 or set(registrations.values()) & {1, 5}:
        raise ValueError(CP_BOOT_V3_DEV_TREE)
    if nodes != _resolved_dev_rows(registrations):
        raise ValueError(CP_BOOT_V3_DEV_TREE)
    if type(other_nodes) is not tuple:
        raise ValueError(CP_BOOT_V3_DEV_TREE)
    for path, kind in other_nodes:
        if kind in {"symlink", "regular", "socket", "fifo", "submount"} or _forbidden_dev_path(path) or path not in {row[0] for row in DEV_ROWS_V3}:
            raise ValueError(CP_BOOT_V3_DEV_TREE)
    if other_nodes:
        raise ValueError(CP_BOOT_V3_DEV_TREE)


